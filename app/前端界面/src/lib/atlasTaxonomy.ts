/**
 * MITRE ATLAS 攻击战术 → 中文语义
 *
 * ---------- 为什么需要这份映射 ----------
 *
 * ATLAS 是**英文**威胁知识库，原始数据里 tactic 只有 `AML.TA0002` 这样的编号，
 * name也只有 "Search Open Technical Databases" 这类英文短语。
 * 直接把编号和英文名甩给用户，等于让人面对一串无解释的符号——
 * 「AML.TA0002」既不知道是什么，也不知道发生在什么时候。
 *
 * ATLAS 的 tactic 编号本身**不是随机的，它就是一条攻击链的时序**：
 * TA0001准备 → TA0002 侦察 → TA0003 资源开发 → TA0004 初始访问
 * → TA0005 执行 → TA0006 持久化 → TA0007 提权 → TA0008 防御规避
 * → TA0009 凭据访问 → TA0010 侦察发现 → TA0011 横向移动
 * → TA0012 数据收集 → TA0013 外泄 → TA0014 产生影响
 *
 * 编号顺序 = 攻击者推进的先后顺序。所以**按编号排序展示**，
 * 用户顺着往下看就理解了「AI 攻击是怎么一步步发生的」，
 * 而不只是看到一堆并列的名词。这正是把编号映射成中文的价值所在。
 *
 * ---------- 名称的权威性 ----------
 *
 * 中文名是**便于理解的意译**，不是官方翻译。因此展示时
 * **英文原名始终保留**（Tooltip 承载），中文只做辅助理解。
 * 赛题要求答辩时若被问到术语，指英文原名即可，不会失真。
 */

